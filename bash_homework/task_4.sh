# Создайте скрипт с функцией, которая принимает в качестве аргумента строку и выводит её с префиксом "Hello, "
greet() {
    local name="$1"
    echo "Hello, $name"
}

# Напишите ещё одну функцию, которая принимает два числа и возвращает их сумму
add_numbers() {
    local a="$1"
    local b="$2"
    local sum=$((a + b))
    echo "$sum"
}

#Вызовите обе функции в скрипте и продемонстрируйте результат
echo "=== Демонстрация функций ==="

echo -n "Введите ваше имя: "
read user_name
greet "$user_name"

echo ""

echo "Введите первое число:"
read num1
echo "Введите второе число:"
read num2

if ! [[ "$num1" =~ ^-?[0-9]+$ ]] || ! [[ "$num2" =~ ^-?[0-9]+$ ]]; then
    echo "Ошибка: введите целые числа."
    exit 1
fi

result=$(add_numbers "$num1" "$num2")
echo "Сумма $num1 и $num2 равна: $result"