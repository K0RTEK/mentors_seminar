# Создайте alias для команды ls -la и назовите его ll
echo "=== Демонстрация alias и автодополнения ==="

echo ""
echo "Создаём временный alias 'll' для 'ls -la'"
alias ll='ls -la'

echo "Проверяем работу alias:"
ll | head -n 5

