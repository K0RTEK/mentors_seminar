echo "=== Управление переменной PATH ==="
echo ""

if [ $# -ne 1 ]; then
    echo "Ошибка: укажите путь для добавления в PATH."
    echo "Использование: $0 <путь_к_директории>"
    exit 1
fi

new_dir="$1"

if [ ! -d "$new_dir" ]; then
    echo "Ошибка: директория '$new_dir' не существует."
    exit 1
fi

echo "Текущее значение PATH:"
echo "$PATH"
echo ""

export PATH="$new_dir:$PATH"

echo "Добавлена директория '$new_dir' в PATH."
echo "Новое значение PATH:"
echo "$PATH"
echo ""

# 2. Объяснение — почему изменения временные
echo "Почему изменения PATH через терминал — временные?"
echo "   Переменные окружения (включая PATH) существуют только в рамках текущей оболочки (процесса)."
echo "   При закрытии терминала или запуске нового — оболочка создаётся заново с 'чистыми' настройками."
echo "   Поэтому изменения, сделанные вручную (например, export PATH=...), теряются."
echo ""

# 3. Как сделать изменения постоянными
echo "Как сделать изменения постоянными:"
echo "   Добавьте строку экспорта в файл ~/.bashrc — он загружается при каждом запуске Bash-оболочки."
echo ""
echo "   Шаги:"
echo "   1. Откройте файл ~/.bashrc:"
echo "      nano ~/.bashrc"
echo "   2. Добавьте в конец файла строку:"
echo "      export PATH=\"$new_dir:\$PATH\""
echo "   3. Сохраните файл (Ctrl+O → Enter → Ctrl+X)"
echo "   4. Примените изменения без перезапуска терминала:"
echo "      source ~/.bashrc"
echo ""

# 4. Демонстрация перезапуска терминала
echo ""
echo "Как перезапустить терминал для применения изменений:"
echo "   После редактирования ~/.bashrc:"
echo "   • Закройте текущий терминал и откройте новый — изменения применятся автоматически."
echo "   • Или выполните в текущем терминале:"
echo "        exec bash"
echo "     Это перезапустит оболочку в том же окне, загрузив новые настройки."
echo ""
